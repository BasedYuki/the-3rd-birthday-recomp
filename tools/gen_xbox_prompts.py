"""Draws the Xbox-style button prompts that replace the PSP ones in the game's font texture
(Esc menu > Button prompts) and writes runtime/src/rt/gpu_sdl3vk/prompts_xbox.h.

The glyphs are drawn here from scratch (circles, pills and letters), nothing is taken from the
game. Each patch is a rectangle of the 512x256 font texture with RGBA pixels:
    python tools/gen_xbox_prompts.py [--preview out.png]
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

SS = 8                                        # supersampling
FONT = "C:/Windows/Fonts/arialbd.ttf"
OUT = os.path.join(os.path.dirname(__file__), "..", "runtime", "src", "rt", "gpu_sdl3vk", "prompts_xbox.h")
Y0, H = 224, 12                               # the button row of the font texture

FACE = [  # (x, letter, colour) for the PSP square, triangle, circle, cross cells
    (171, "X", (64, 140, 255)), (188, "Y", (255, 196, 0)),
    (205, "B", (240, 60, 50)), (222, "A", (90, 200, 60)),
]
PILL = [(341, 29, "LT"), (375, 29, "RT"), (409, 44, "VIEW"), (460, 44, "MENU")]

def text_mask(draw_size, txt, px):
    f = ImageFont.truetype(FONT, px * SS)
    m = Image.new("L", draw_size, 0); d = ImageDraw.Draw(m)
    l, t, r, b = d.textbbox((0, 0), txt, font=f)
    d.text(((draw_size[0] - (r - l)) / 2 - l, (draw_size[1] - (b - t)) / 2 - t), txt, font=f, fill=255)
    return m

def face(letter, col):
    s = (12 * SS, 12 * SS)
    shape = Image.new("L", s, 0); ImageDraw.Draw(shape).ellipse((0, 0, s[0] - 1, s[1] - 1), fill=255)
    let = text_mask(s, letter, 9)
    im = Image.new("RGBA", s, col + (255,))
    im.paste((24, 24, 24, 255), (0, 0), let)
    im.putalpha(shape)
    return im.resize((12, 12), Image.LANCZOS)

def pill(w, txt):
    s = (w * SS, H * SS)
    shape = Image.new("L", s, 0)
    ImageDraw.Draw(shape).rounded_rectangle((0, 0, s[0] - 1, s[1] - 1), radius=s[1] // 2, fill=255)
    let = text_mask(s, txt, 9)
    a = Image.composite(Image.new("L", s, 0), shape, let)          # letters cut out, like the original
    im = Image.new("RGBA", s, (255, 255, 255, 255)); im.putalpha(a)
    return im.resize((w, H), Image.LANCZOS)

patches = [(x, face(l, c)) for x, l, c in FACE] + [(x, pill(w, t)) for x, w, t in PILL]

if "--preview" in sys.argv:
    p = Image.new("RGBA", (520, 40), (40, 40, 70, 255))
    for x, im in patches: p.alpha_composite(im, (x - 165, 14))
    p.resize((p.width * 4, p.height * 4), Image.NEAREST).save(sys.argv[sys.argv.index("--preview") + 1])

with open(OUT, "w", newline="\n") as f:
    f.write("/* Generated by tools/gen_xbox_prompts.py: Xbox-style button prompts drawn into the font\n"
            " * texture (Esc menu > Button prompts). Drawn from scratch, no game data. */\n")
    f.write("typedef struct { short x, y, w, h; const unsigned int *px; } XboxPatch;\n")
    for i, (x, im) in enumerate(patches):
        px = [r | g << 8 | b << 16 | a << 24 for r, g, b, a in im.getdata()]
        f.write("static const unsigned int s_xbp%d[%d] = {" % (i, len(px)))
        for j, v in enumerate(px):
            f.write(("\n    " if j % 8 == 0 else " ") + "0x%08x," % v)
        f.write("\n};\n")
    f.write("static const XboxPatch s_xbox_patch[%d] = {\n" % len(patches))
    for i, (x, im) in enumerate(patches):
        f.write("    { %d, %d, %d, %d, s_xbp%d },\n" % (x, Y0, im.width, im.height, i))
    f.write("};\n")
print("wrote", OUT)
