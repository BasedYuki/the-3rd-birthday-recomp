"""Code mods: mods/<name>/mod.toml + C files, compiled into the game by scripts/build.sh.

    python tools/mods_gen.py --hooks          comma list of all enabled mods' hook addresses
    python tools/mods_gen.py --gen <outdir>   writes mods_gen.c, mods_hooks.h, mods_srcs.txt

mod.toml:
    name = "Wider field of view"
    enabled = true
    [hooks]                     # functions whose entry calls the mod (names -> MODHOOK_<NAME>)
    cam_setup = 0x08B435B8

Each mod's C files are compiled with mod_hook renamed per mod, so every mod defines
    int mod_hook(CpuState *s, uint32_t addr)
and returns 1 to replace the function (after setting s->r[2]/r[3] or whatever it returns),
0 to let it run. See mods/README.md.
"""

import glob
import os
import re
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def mods():
    out = []
    for toml in sorted(glob.glob(os.path.join(ROOT, "mods", "*", "mod.toml"))):
        with open(toml, "rb") as f:
            data = tomllib.load(f)
        if not data.get("enabled", True):
            continue
        d = os.path.dirname(toml)
        mid = re.sub(r"[^A-Za-z0-9_]", "_", os.path.basename(d))
        out.append((mid, d, data))
    return out


def main():
    ms = mods()
    if "--hooks" in sys.argv:
        print(",".join("0x%08x" % v for _, _, m in ms for v in m.get("hooks", {}).values()))
        return
    outdir = sys.argv[sys.argv.index("--gen") + 1]
    hdr = ["/* Generated by tools/mods_gen.py from mods/*/mod.toml -- do not edit. */", "#pragma once"]
    seen = {}
    for mid, _, m in ms:
        for name, v in m.get("hooks", {}).items():
            key = name.upper()
            if seen.get(key, v) != v:
                sys.exit(f"mods: hook name {name} is used for two different addresses")
            seen[key] = v
    for key, v in seen.items():
        hdr.append("#define MODHOOK_%s 0x%08Xu" % (key, v))
    open(os.path.join(outdir, "mods_hooks.h"), "w").write("\n".join(hdr) + "\n")
    c = ["/* Generated by tools/mods_gen.py -- do not edit. */", '#include "recomp.h"']
    for mid, _, _ in ms:
        c.append(f"int mod_{mid}_hook(CpuState *s, uint32_t addr);")
    if ms:
        c.append("int sr_mods_hook(CpuState *s, uint32_t addr) {")
        for mid, _, _ in ms:
            c.append(f"    if (mod_{mid}_hook(s, addr)) return 1;")
        c.append("    return 0;")
        c.append("}")
    open(os.path.join(outdir, "mods_gen.c"), "w").write("\n".join(c) + "\n")
    with open(os.path.join(outdir, "mods_srcs.txt"), "w") as f:
        for mid, d, _ in ms:
            for src in sorted(glob.glob(os.path.join(d, "*.c"))):
                f.write(f"{mid} {src.replace(os.sep, '/')}\n")
    print(f"mods: {len(ms)} code mod(s): " + ", ".join(m.get("name", mid) for mid, _, m in ms) if ms else "mods: none")


if __name__ == "__main__":
    main()
